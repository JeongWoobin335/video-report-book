"""테스트용 가상 입력(전사 + 화면)을 만든다. 실제 영상이 없을 때 스킬을 시험하기 위한 것.

사용: python build_samples.py   →  evals/files/{meeting-beta-schedule, lecture-http-caching, lecture-audio-only}/
일부러 넣어 둔 함정은 각 샘플 위의 주석 참고.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "files"


def t(ts):
    m, s = ts.split(":")
    return int(m) * 60 + int(s)


def write(name, duration, lines, screens):
    """lines: (시각, 화자, 말[, 신뢰도]). 발화의 끝은 다음 발화 시작 직전으로 잡는다."""
    folder = OUT / name
    folder.mkdir(parents=True, exist_ok=True)
    segs = []
    for i, line in enumerate(lines):
        start = t(line[0])
        end = t(lines[i + 1][0]) - 0.5 if i + 1 < len(lines) else t(duration)
        seg = {"start": start, "end": end, "text": line[2], "speaker": line[1]}
        if len(line) > 3:
            seg["confidence"] = line[3]
        segs.append(seg)
    (folder / "transcript.json").write_text(
        json.dumps({"language": "ko", "duration": t(duration), "segments": segs}, ensure_ascii=False, indent=1),
        encoding="utf-8")
    if screens is not None:
        (folder / "screens.json").write_text(
            json.dumps({"screens": [dict(s, time=t(s["time"])) for s in screens]}, ensure_ascii=False, indent=1),
            encoding="utf-8")


